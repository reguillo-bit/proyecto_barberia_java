    public void capturardatos()
    {
        if(!txtnombre.getText().isEmpty() || !txtedad.getText().isEmpty())
        {
            nombre = txtnombre.getText();
            edad = Integer.valueOf(txtedad.getText());
        }
        else
        {
            JOptionPane.showMessageDialog(rootPane, "campos Vacío!!");
        }
        
    }
    public void agregarbarbero()
    {
        
        if(!txtnombre.getText().isEmpty() || !txtedad.getText().isEmpty())
        {
            capturardatos();
            try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
            {
                PreparedStatement pstm = con.prepareCall("call agregarbarbero(?,?)");
                pstm.setString(1, nombre);
                pstm.setInt(2, edad);
                pstm.executeQuery();
                JOptionPane.showMessageDialog(rootPane, "agregado correctamente");
            }
            catch(SQLException e)
            {
                JOptionPane.showMessageDialog(rootPane, e.toString());
            }
        }
        else
        {
            JOptionPane.showMessageDialog(rootPane, "campos Vacío!!");
        }
    }

