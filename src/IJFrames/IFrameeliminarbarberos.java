    private void tblbarberosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblbarberosMouseClicked
        // TODO add your handling code here:
        int clic = tblbarberos.rowAtPoint(evt.getPoint());
        if(clic < 0)
        {
            return;
        }
        fila = Integer.parseInt(tblbarberos.getValueAt(clic, 0).toString()); // id del registro
        try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
        {
            Statement stm = con.createStatement();
            ResultSet rs = stm.executeQuery("select * from verbarbero");
            ResultSetMetaData  rstm = rs.getMetaData();
            
            while(rs.next())
            {
                id = rs.getInt("ID");
                String nombre = rs.getString("NOMBRE");
                
                if(id == fila)
                {
                    lblnombre.setText(nombre);
                    
                    break;
                }
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }//GEN-LAST:event_tblbarberosMouseClicked

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if(fila == 0)
        {
            JOptionPane.showMessageDialog(rootPane, "Seleccione un barbero de la tabla");
            return;
        }
        if(JOptionPane.showConfirmDialog(rootPane, "Se eliminara el barbero " + lblnombre.getText()
                + ". Desea continuar?", "Confirmar",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION)
        {
            return;
        }
        eliminar();
        fila = 0;
        lblnombre.setText("Nombre");
        llenartabla();
    }//GEN-LAST:event_jButton1ActionPerformed


