    public void llenarcombo()
    {
        jComboBox1.removeAllItems();
        jComboBox1.addItem("seleccione...");
        b.clear();
        try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
        {
            Statement stm = con.createStatement();
            ResultSet rs = stm.executeQuery("SELECT * FROM verbarbero");
            while(rs.next())
            {
                int idbarbero = rs.getInt("ID");
                String nombrebarbero = rs.getString("NOMBRE");
                int edadbarbero = rs.getInt("EDAD");
                b.add(new barbero(idbarbero,nombrebarbero,edadbarbero));
                jComboBox1.addItem(nombrebarbero);
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }

    // muestra los pagos del barbero seleccionado y el total a pagarle
    public void llenartabla()
    {
        long total = 0;
        int indice = jComboBox1.getSelectedIndex();
        DefaultTableModel modelo = new DefaultTableModel();
        if(indice <= 0)
        {
            String[] titulos = {"FECHA","CLIENTE","SERVICIO","VALOR","PAGO"};
            for(String t : titulos)
            {
                modelo.addColumn(t);
            }
            jTable1.setModel(modelo);
            lbltotal.setText("Total a pagar: 0");
            return;
        }
        try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
        {
            PreparedStatement pstm = con.prepareCall("call pagos_por_barbero(?)");
            pstm.setInt(1, b.get(indice - 1).getId());
            ResultSet rs = pstm.executeQuery();
            ResultSetMetaData rsmt = rs.getMetaData();
            for(int i = 1; i <= rsmt.getColumnCount(); i++)
            {
                modelo.addColumn(rsmt.getColumnLabel(i));
            }
            while(rs.next())
            {
                String FECHA = rs.getString("FECHA");
                String CLIENTE = rs.getString("CLIENTE");
                String SERVICIO = rs.getString("SERVICIO");
                int VALOR = rs.getInt("VALOR");
                int PAGO = rs.getInt("PAGO");
                total += PAGO;
                modelo.addRow(new Object[]{FECHA, CLIENTE, SERVICIO, VALOR, PAGO});
            }
            jTable1.setModel(modelo);
            lbltotal.setText("Total a pagar: " + total);
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }

