    public void actualizarbarbero(){
        try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
        {
            if(!txtedad.getText().isEmpty() || !txtnombre.getText().isEmpty())
            {
                int id = fila;
                String nombre = txtnombre.getText();
                int edad = Integer.valueOf(txtedad.getText());


                PreparedStatement pstm = con.prepareCall("call acualizarbarbero(?,?,?)");
                pstm.setInt(1, id);
                pstm.setString(2, nombre);
                pstm.setInt(3, edad);
                pstm.executeQuery();
                
                JOptionPane.showMessageDialog(rootPane, "Actualizado correctamente");
                
            }
            else
            {
                JOptionPane.showMessageDialog(rootPane, "datos erroneos!!");
            }
            
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }
    public void llenartablapago()
    {
        try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
        {
            DefaultTableModel modelo = new DefaultTableModel();
            Statement stm = con.createStatement();
            ResultSet rs = stm.executeQuery("select * from verbarbero");
            ResultSetMetaData rstm = rs.getMetaData();
            
            for(int i =1; i <= rstm.getColumnCount();i++)
            {
                modelo.addColumn(rstm.getColumnLabel(i));
            }
            
            while(rs.next())
            {
                int ID = rs.getInt("ID");
                String NOMBRE = rs.getString("NOMBRE");
                int EDAD = rs.getInt("EDAD");
                
                modelo.addRow(new Object[]{ID,NOMBRE,EDAD});
            }
            
            tbleditar.setModel(modelo);
        
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    
    }

