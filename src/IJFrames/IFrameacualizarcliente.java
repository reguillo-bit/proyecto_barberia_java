    public void actualizar(){
    
        try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
        {
            int id = fila;
            String n = txtnombre.getText();
            int ed = Integer.valueOf(txtedad.getText());
            if(!txtnombre.getText().isEmpty() || !txtedad.getText().isEmpty()){
                PreparedStatement pstm = con.prepareCall("call acualizarcliente(?,?,?)");
                pstm.setInt(1, id);
                pstm.setString(2,n);
                pstm.setInt(3, ed);
                pstm.executeQuery();
                
                llenartabla();
                JOptionPane.showMessageDialog(rootPane, "Cliente actualizado correctamente");
            }
            else
            {
                JOptionPane.showMessageDialog(rootPane, "Error de datos erroneos!");
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
    }
    
    public void llenartabla(){
    
        try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
        {
            DefaultTableModel modelo = new DefaultTableModel();
            
            Statement stm = con.createStatement();
            ResultSet rs = stm.executeQuery("select * from verclientes");
            ResultSetMetaData  rstm = rs.getMetaData();
            
            for(int i=1; i <= rstm.getColumnCount();i++)
            {
                modelo.addColumn(rstm.getColumnLabel(i));
            }
            while(rs.next())
            {
                int id = rs.getInt("ID");
                String nombre = rs.getString("NOMBRE");
                int edad = rs.getInt("EDAD");
                modelo.addRow(new Object[]{id,nombre,edad});
            }
            tblclientes.setModel(modelo);
        
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }   
    }
