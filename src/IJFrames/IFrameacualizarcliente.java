    private void tblclientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblclientesMouseClicked
        // TODO add your handling code here:
        int clic = tblclientes.rowAtPoint(evt.getPoint());
        if(clic < 0)
        {
            return;
        }
        fila = Integer.parseInt(tblclientes.getValueAt(clic, 0).toString()); // id del registro
        try(Connection con = DriverManager.getConnection(conexion.getUrl(),conexion.getUser(),conexion.getPassword()))
        {
            Statement stm = con.createStatement();
            ResultSet rs = stm.executeQuery("select * from verclientes");
            ResultSetMetaData  rstm = rs.getMetaData();
            
            while(rs.next())
            {
                int id = rs.getInt("ID");
                    nombre = rs.getString("NOMBRE");
                edad = rs.getInt("EDAD");
                
                if(id == fila)
                {
                    txtnombre.setText(nombre);
                    txtedad.setText(String.valueOf(edad));
                    break;
                }
            }
        }
        catch(SQLException e)
        {
            JOptionPane.showMessageDialog(rootPane, e.toString());
        }
        
    }//GEN-LAST:event_tblclientesMouseClicked

